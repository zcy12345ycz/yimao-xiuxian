/* ============ 根据进度，挑今天说的话 ============ */
function pickGufengTalk(){
  const toldIds = s.toldTalkIds || [];
  // 优先出主线，按顺序
  const nextMain = GUFENG_TALKS.find(t => t.type === 'main' && !toldIds.includes(t.id));
  if(nextMain) return nextMain;
  // 主线出完了，随机抽日常
  const dailies = GUFENG_TALKS.filter(t => t.type === 'daily');
  return dailies[Math.floor(Math.random() * dailies.length)];
}